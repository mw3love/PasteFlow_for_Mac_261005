import Foundation

/// pasteboard type 목록으로 항목 종류·미리보기·저장 여부를 정한다(AppKit 없이 테스트 가능하게 분리).
public enum ClipClassifier {
    public static let plainText = "public.utf8-plain-text"
    public static let html = "public.html"
    public static let rtf = "public.rtf"
    public static let fileURL = "public.file-url"
    public static let imageTypes = ["public.png", "public.tiff", "public.jpeg", "public.heic"]

    /// 비밀번호 관리자 등이 "기록하지 말라"고 표시하는 형식(nspasteboard.org 관례).
    public static let skipMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// 형식 하나가 이보다 크면 저장하지 않는다(예: 큰 TIFF). 다른 형식은 그대로 둔다.
    public static let maxFormatBytes = 32 * 1024 * 1024

    public static func shouldSkip(types: [String]) -> Bool {
        types.contains { skipMarkers.contains($0) }
    }

    /// 기록할 내용이 없는 복사인가(예: 빈 글자만 있는 클립보드).
    public static func isEmpty(formats: [String: Data]) -> Bool {
        let meaningful = formats.filter { type, data in
            if type == plainText { return !(String(data: data, encoding: .utf8) ?? "").trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
            return !data.isEmpty
        }
        return meaningful.isEmpty
    }

    public static func kind(for types: [String]) -> ClipItem.Kind {
        let set = Set(types)
        if set.contains(fileURL) { return .file }
        let hasImage = imageTypes.contains { set.contains($0) }
        if hasImage && !set.contains(plainText) { return .image }
        if set.contains(html) { return .html }
        if set.contains(rtf) { return .rtf }
        if set.contains(plainText) { return .text }
        return hasImage ? .image : .other
    }

    /// 패널·HUD에 보일 짧은 글자.
    public static func preview(formats: [String: Data], kind: ClipItem.Kind, imageSize: (Int, Int)? = nil) -> String {
        if kind == .file, let d = formats[fileURL], let s = String(data: d, encoding: .utf8), let url = URL(string: s) {
            return url.lastPathComponent
        }
        if kind == .image {
            if let (w, h) = imageSize { return "이미지 \(w)×\(h)" }
            return "이미지"
        }
        if let d = formats[plainText], let s = String(data: d, encoding: .utf8) {
            let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
            return String(trimmed.prefix(500))
        }
        return kind == .other ? "(알 수 없는 형식)" : kind.rawValue.uppercased()
    }
}
